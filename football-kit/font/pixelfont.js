const ROWS = {};
for (const [k, v] of Object.entries(G)) ROWS[k] = v.split(' ').map(r => [...r].map(Number));

export const GLYPH_W = 5, GLYPH_H = 7, ADVANCE = 6; // 1 px letter spacing

export function measurePixelText(text, px = 4) {
  return Math.max(0, String(text).length * ADVANCE - 1) * px;
}

export function drawPixelText(ctx, text, x, y, { px = 4, color = '#fff', align = 'left', shadow = null, shadowOff = 1 } = {}) {
  const s = String(text).toUpperCase(), w = measurePixelText(s, px);
  let x0 = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
  x0 = Math.round(x0); y = Math.round(y);
  const pass = (ox, oy, col) => {
    ctx.fillStyle = col;
    [...s].forEach((ch, i) => {
      const g = ROWS[ch] || ROWS['?'];
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c]) ctx.fillRect(x0 + (i * ADVANCE + c) * px + ox, y + r * px + oy, px, px);
    });
  };
  if (shadow) pass(shadowOff * px, shadowOff * px, shadow);
  pass(0, 0, color);
  return w;
}
